//! 候选窗上的鼠标操作：窗口是 Server 自绘的，这些操作不经过按键，由 UI 线程发回 Router。

/// 用户在候选窗上做的事。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CandidateEvent {
    /// 鼠标移到第 `index` 格上（帧里的页内下标，从 0 起）：高亮挪过去。
    Hover(usize),

    /// 鼠标移出候选窗：不再指着任何一格。
    HoverLeft,

    /// 单击第 `index` 格：这一格上屏。
    Commit(usize),

    /// 右键单击候选窗：`Some(index)` 是点在某一格上（帧里的页内下标），`None` 是点在空白处。
    /// 不在释义选择界面时：开着「启用翻译 Tip」就等于按下 `Ctrl + 反引号`（上屏那一格的译文 /
    /// 进多释义选择），没开着什么都不做；在释义选择界面里则一律等于 `Esc`（取消选择）。
    Translate(Option<usize>),

    /// 鼠标中键单击候选窗：等于按下 `Shift + 反引号`（念高亮候选的译文）。
    /// 在释义选择界面里念高亮那条释义。点在哪一格都一样，念的是高亮那个。
    Speak,

    /// 鼠标滚轮（不带修饰键）：`+1` 下一页、`-1` 上一页。展开「更多候选项」时一页就是一整屏。
    /// Ctrl + 滚轮不在这里——那是缩放整个候选窗，由窗口自己就地处理。
    Page(isize),
}
